/// Bundles the Dart-only corpus cases in `test/corpus/dart/` into
/// `test/corpus/dart.g.dart`, so they run where there is no file access
/// (chrome, wasm). Run after editing a case:
///
///     dart run tool/bundle_cases.dart
library;

import 'dart:io';

import 'sync_corpus.dart' show literal;

const _source = 'test/corpus/dart';
const _target = 'test/corpus/dart.g.dart';

void main() {
  File(_target).writeAsStringSync(bundle(_source));
  final result = Process.runSync(Platform.resolvedExecutable, [
    'format',
    _target,
  ]);
  if (result.exitCode != 0) {
    stderr.writeln(result.stderr);
    exitCode = 1;
  }
}

/// The library holding every case under [source], unformatted.
String bundle(String source) {
  final directories =
      Directory(source).listSync().whereType<Directory>().toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  final out = StringBuffer()
    ..writeln('// Generated by tool/bundle_cases.dart from test/corpus/dart.')
    ..writeln('// Do not edit; run the tool instead.')
    ..writeln()
    ..writeln(
      '/// The Dart-only conformance cases by name, each mapping file name to',
    )
    ..writeln('/// text.')
    ..writeln('const dartCases = <String, Map<String, String>>{');
  for (final directory in directories) {
    final name = directory.uri.pathSegments.lastWhere(
      (part) => part.isNotEmpty,
    );
    out.writeln('  ${literal(name)}: {');
    final files = directory.listSync().whereType<File>().toList()
      ..sort((a, b) => a.path.compareTo(b.path));
    for (final file in files) {
      out.writeln(
        '    ${literal(file.uri.pathSegments.last)}: '
        '${literal(file.readAsStringSync())},',
      );
    }
    out.writeln('  },');
  }
  out.writeln('};');
  return out.toString();
}
